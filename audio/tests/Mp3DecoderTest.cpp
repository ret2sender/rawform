// Open failure: a missing path yields nullptr and a non-empty error.
void testOpenFailure() {
    std::string err;
    std::unique_ptr<IDecoder> dec =
        Mpg123Decoder::open("rf_mp3_does_not_exist.mp3", &err);
    CHECK(dec == nullptr);
    CHECK(!err.empty());
}

