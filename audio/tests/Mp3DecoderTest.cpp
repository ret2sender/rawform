// Writes a byte blob to a path so libmpg123 can open it as a normal file.
bool writeTempFile(const std::string& path, const unsigned char* data,
                   std::size_t len) {
    std::FILE* f = std::fopen(path.c_str(), "wb");
    if (!f) {
        return false;
    }
    const std::size_t w = std::fwrite(data, 1, len, f);
    std::fclose(f);
    return w == len;
}

// 64-bit FNV-1a over the raw bytes of the decoded float buffer. Used only to
// compare two decodes produced by the same library in the same process, so the
// exact float encoding never matters across machines.
std::uint64_t fnv1a(const std::vector<float>& v) {
    std::uint64_t       h     = 0xcbf29ce484222325ull;
    const auto*         p     = reinterpret_cast<const unsigned char*>(v.data());
    const std::size_t   bytes = v.size() * sizeof(float);
    for (std::size_t i = 0; i < bytes; ++i) {
        h ^= p[i];
        h *= 1099511628211ull;
    }
    return h;
}

// Decodes to EOS into a flat interleaved float buffer, 1024 frames at a time.
std::vector<float> decodeAll(IDecoder& dec) {
    const std::size_t  ch = dec.format().channels;
    std::vector<float> out;
    std::vector<float> block(1024 * ch);
    for (;;) {
        const std::size_t got = dec.read(block.data(), 1024);
        if (got == 0) {
            break;
        }
        out.insert(out.end(), block.begin(),
                   block.begin() + static_cast<std::ptrdiff_t>(got * ch));
        if (got < 1024) {
            break;
        }
    }
    return out;
}

// One MPEG-1 Layer III frame is 1152 samples; seek precision and gapless
// boundaries are good to roughly a frame, so structural frame-count checks use a
// few frames of slack rather than demanding an exact landing.
constexpr std::uint64_t kFrameSlack = 1152 * 3;

bool nearWithin(std::uint64_t a, std::uint64_t b, std::uint64_t slack) {
    return (a > b ? a - b : b - a) <= slack;
}

// ---------------------------------------------------------------------------
// CBR fixture: full property surface, the exact CBR bitrate, gapless length
// agreement, and decode determinism.
void testCbrProperties() {
    const std::string path = "rf_mp3_cbr.mp3";
    CHECK(writeTempFile(path, kCbrMp3, kCbrMp3_len));

    std::string err;
    std::unique_ptr<IDecoder> dec = Mpg123Decoder::open(path, &err);
    CHECK(dec != nullptr);
    if (dec) {
        CHECK(dec->format() == (AudioFormat{44100, 1}));

        const SourceInfo si = dec->sourceInfo();
        CHECK(si.codec == Codec::Mp3);
        CHECK(si.bitsPerSample == 0);  // lossy convention
        CHECK(si.bitrateKbps == 128);  // exact for CBR

        const std::uint64_t total = dec->totalFrames();
        CHECK(total > 0);  // Xing/Info length, no scan

        const std::vector<float> a = decodeAll(*dec);
        CHECK(!a.empty());

        // Gapless: the count actually decoded agrees with the reported length to
        // within a frame.
        const std::uint64_t decoded =
            static_cast<std::uint64_t>(a.size() / dec->format().channels);
        CHECK(nearWithin(decoded, total, kFrameSlack));

        // Determinism: two fresh sequential decodes are bit-identical. (Seeking
        // is checked separately; an MP3 seek, even back to 0, is not guaranteed
        // bit-identical to a sequential decode because the layer-III synthesis
        // carries inter-frame state that a fresh open warms up and a seek cannot
        // perfectly reproduce, so we do NOT assert seek(0) == sequential.)
        std::unique_ptr<IDecoder> dec2 = Mpg123Decoder::open(path);
        CHECK(dec2 != nullptr);
        if (dec2) {
            CHECK(fnv1a(decodeAll(*dec2)) == fnv1a(a));
        }

        // seek(0) is still a valid rewind: decoding from it yields about the full
        // length again (structural, not bit-exact).
        CHECK(dec->seek(0));
        const std::uint64_t afterRewind =
            static_cast<std::uint64_t>(decodeAll(*dec).size() / dec->format().channels);
        CHECK(nearWithin(afterRewind, total, kFrameSlack));
    }
    std::remove(path.c_str());
}

