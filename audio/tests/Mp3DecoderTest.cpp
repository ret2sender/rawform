// ---------------------------------------------------------------------------
// Seek lands near the request and is reproducible. Content-agnostic: it checks
// the count of frames remaining after a seek, which must fall as the target
// rises, plus that repeating a seek reproduces the same decoded bytes.
void testSeekLandsNear() {
    const std::string path = "rf_mp3_seek.mp3";
    CHECK(writeTempFile(path, kCbrMp3, kCbrMp3_len));

    std::unique_ptr<IDecoder> dec = Mpg123Decoder::open(path);
    CHECK(dec != nullptr);
    if (dec) {
        CHECK(dec->seekable());
        const std::uint64_t total = dec->totalFrames();
        CHECK(total > 0);

        const std::uint64_t targets[] = {0, total / 4, total / 2, (3 * total) / 4,
                                         total};
        std::uint64_t       prevRemaining = total + kFrameSlack + 1;
        for (std::uint64_t t : targets) {
            CHECK(dec->seek(t));
            const std::uint64_t remaining =
                static_cast<std::uint64_t>(decodeAll(*dec).size() /
                                           dec->format().channels);
            // Lands near: about (total - t) frames are left.
            CHECK(nearWithin(remaining, total - t, kFrameSlack));
            // Monotonic: a later target never leaves MORE frames than an earlier
            // one (allowing the per-seek slack at the boundary).
            CHECK(remaining <= prevRemaining + kFrameSlack);
            prevRemaining = remaining;
        }

        // Reproducible: the same seek twice yields identical decoded bytes.
        const std::uint64_t mid = total / 2;
        CHECK(dec->seek(mid));
        std::vector<float> first(512 * dec->format().channels);
        const std::size_t  n1 = dec->read(first.data(), 512);
        CHECK(dec->seek(mid));
        std::vector<float> second(512 * dec->format().channels);
        const std::size_t  n2 = dec->read(second.data(), 512);
        CHECK(n1 == n2);
        first.resize(n1 * dec->format().channels);
        second.resize(n2 * dec->format().channels);
        CHECK(fnv1a(first) == fnv1a(second));
    }
    std::remove(path.c_str());
}

